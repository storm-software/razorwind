export function renderInstallMd(
  styles: Array<{ name: string; fileName: string }>
): string {
  const files = styles
    .map(style => `- \`${style.fileName}\` — ${style.name}`)
    .join("\n");
  const first = styles[0]!;

  return `# Using the generated MapLibre styles

Generated by \`@razorwind/maplibre\`.

## Files

${files}

## Load a style

Serve the JSON file with your app, then pass its URL to MapLibre GL JS:

\`\`\`ts
import maplibre from "maplibre-gl";

const map = new maplibre.Map({
  container: "map",
  style: "/${first.fileName}"
});
\`\`\`

To switch an existing map to an imported style object, call \`map.setStyle(style)\`.
Make sure every tile, sprite, and glyph URL in the style is reachable by the browser.
`;
}
