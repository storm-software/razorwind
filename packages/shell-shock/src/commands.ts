/**
 * Render the shared snapshot module that bakes the design system into the
 * build. `JSON.parse` of a string literal keeps the module cheap to compile
 * even for large design systems.
 */
export function renderSnapshotModule(snapshot: DesignSystemSnapshot): string {
  const json = JSON.stringify(JSON.stringify(snapshot));

  return `${GENERATED_HEADER}
import type { DesignSystemSnapshot } from "${RUNTIME_MODULE}";

/**
 * The extracted design system baked into this CLI at build time.
 */
export const designSystem: DesignSystemSnapshot = Object.freeze(
  JSON.parse(${json})
) as DesignSystemSnapshot;
`;
}

/**
 * Resolve which commands are enabled from the plugin `commands` option.
 */
export function selectCommands(
  commands:
    | DesignSystemCommandId[]
    | Partial<Record<DesignSystemCommandId, boolean>>
    | undefined
): DesignSystemCommand[] {
  if (!commands) {
    return DESIGN_SYSTEM_COMMANDS;
  }
  if (Array.isArray(commands)) {
    const ids = new Set(commands);

    return DESIGN_SYSTEM_COMMANDS.filter(command => ids.has(command.id));
  }

  return DESIGN_SYSTEM_COMMANDS.filter(
    command => commands[command.id] !== false
  );
}
