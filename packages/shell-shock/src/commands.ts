/** Module specifier the generated commands import runtime helpers from. */
export const RUNTIME_MODULE = "@razorwind/shell-shock/runtime";

/** Directory (under the Shell Shock entry path) holding shared modules. */
export const SHARED_DIRECTORY = "razorwind";

/** File name of the generated design-system snapshot module. */
export const SNAPSHOT_MODULE = "design-system";

/**
 * Static metadata for a contributed design-system command.
 */
export interface DesignSystemCommand {
  id: DesignSystemCommandId;
  title: string;
  description: string;
  icon: string;
  alias?: string[];
  tags: string[];
  /** Render the `command.ts` source. */
  render: (context: CommandRenderContext) => string;
}

export interface CommandRenderContext {
  /** Relative import specifier for the snapshot module. */
  snapshotImport: string;
  /** Design-system title for help / tool descriptions. */
  title: string;
}

const GENERATED_HEADER = `/* eslint-disable */
/* oxlint-disable */
// biome-ignore lint: disable

// Generated by @razorwind/shell-shock
// Please do not edit this file manually - it will be automatically overwritten
// the next time the generator is run.
`;

const PRINT_HELPERS = `
function print(result: unknown): void {
  process.stdout.write(\`\${typeof result === "string" ? result : JSON.stringify(result, null, 2)}\\n\`);
}
`;

function searchCommandSource(
  context: CommandRenderContext,
  options: {
    interfaceName: string;
    fn: string;
    subject: string;
    example: string;
    extraOptions?: string;
    extraArgs?: string;
  }
): string {
  return `${GENERATED_HEADER}
import { ${options.fn}, isSearchError } from "${RUNTIME_MODULE}";
import { designSystem } from "${context.snapshotImport}";

/**
 * Options for the \`${options.subject}\` search.
 */
export interface ${options.interfaceName} {
  /**
   * One or more search terms (fuzzy match). Example: ${options.example}.
   */
  terms: string[];

  /**
   * Maximum matches per term.
   *
   * @defaultValue 2
   */
  limit?: number;
${options.extraOptions ?? ""}}
${PRINT_HELPERS}
/**
 * Search the ${context.title} ${options.subject} and print matching records as JSON.
 */
export default async function handler(options: ${options.interfaceName}) {
  const result = ${options.fn}(designSystem, {
    terms: options.terms ?? [],
    limit: options.limit${options.extraArgs ?? ""}
  });

  print(result);
  if (isSearchError(result)) {
    process.exitCode = 1;
  }
}
`;
}

function listCommandSource(
  context: CommandRenderContext,
  options: { fn: string; subject: string }
): string {
  return `${GENERATED_HEADER}
import { ${options.fn} } from "${RUNTIME_MODULE}";
import { designSystem } from "${context.snapshotImport}";
${PRINT_HELPERS}
/**
 * Print every ${context.title} ${options.subject} record as JSON.
 */
export default async function handler() {
  print(${options.fn}(designSystem));
}
`;
}

